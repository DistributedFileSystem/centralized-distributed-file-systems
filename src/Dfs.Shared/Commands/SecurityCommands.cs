using Dfs.Shared.Messages;

namespace Dfs.Shared.Commands;

/// <summary>Create a user with a pre-computed PBKDF2-SHA256 hash.</summary>
/// <param name="UserId">Id of the new user.</param>
/// <param name="Username">Login name.</param>
/// <param name="PasswordHash">Hash computed by the caller.</param>
/// <param name="Salt">Salt chosen by the caller.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record CreateUser(string UserId, string Username, string PasswordHash, string Salt, DateTime At) : IMetadataCommand;

/// <summary>Disable or enable a user.</summary>
/// <param name="UserId">Id of the user.</param>
/// <param name="Disabled">True to disable.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record SetUserDisabled(string UserId, bool Disabled, DateTime At) : IMetadataCommand;

/// <summary>Replace the password hash of a user.</summary>
/// <param name="UserId">Id of the user.</param>
/// <param name="PasswordHash">Hash computed by the caller.</param>
/// <param name="Salt">Salt chosen by the caller.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record ResetPassword(string UserId, string PasswordHash, string Salt, DateTime At) : IMetadataCommand;

/// <summary>Create a group.</summary>
/// <param name="GroupId">Id of the new group.</param>
/// <param name="Name">Name of the group.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record CreateGroup(string GroupId, string Name, DateTime At) : IMetadataCommand;

/// <summary>Add or remove a group member.</summary>
/// <param name="GroupId">Id of the group.</param>
/// <param name="UserId">Id of the user.</param>
/// <param name="Member">True to add, false to remove.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record SetGroupMember(string GroupId, string UserId, bool Member, DateTime At) : IMetadataCommand;

/// <summary>Create a role.</summary>
/// <param name="RoleId">Id of the new role.</param>
/// <param name="Name">Name of the role.</param>
/// <param name="Scope">System or item scope.</param>
/// <param name="Permissions">Permission names.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record CreateRole(string RoleId, string Name, RoleScope Scope, ValueList<string> Permissions, DateTime At) : IMetadataCommand;

/// <summary>Replace the permissions of a role.</summary>
/// <param name="RoleId">Id of the role.</param>
/// <param name="Permissions">The new permission names.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record UpdateRole(string RoleId, ValueList<string> Permissions, DateTime At) : IMetadataCommand;

/// <summary>Create a grant; ItemId null means a system grant.</summary>
/// <param name="GrantId">Id of the new grant.</param>
/// <param name="RoleId">Id of the role.</param>
/// <param name="SubjectType">User or group.</param>
/// <param name="SubjectId">Id of the user or group.</param>
/// <param name="ItemId">Id of the item; null for a system grant.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record SetGrant(string GrantId, string RoleId, SubjectType SubjectType, string SubjectId, string? ItemId, DateTime At) : IMetadataCommand;

/// <summary>Remove a grant.</summary>
/// <param name="GrantId">Id of the grant.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record RevokeGrant(string GrantId, DateTime At) : IMetadataCommand;

/// <summary>Store a session created for a user.</summary>
/// <param name="SessionToken">The session token (generated by the caller).</param>
/// <param name="UserId">Id of the user.</param>
/// <param name="ExpiresAt">UTC time the session expires.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record CreateSession(string SessionToken, string UserId, DateTime ExpiresAt, DateTime At) : IMetadataCommand;

/// <summary>Remove a session.</summary>
/// <param name="SessionToken">The session token.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record DeleteSession(string SessionToken, DateTime At) : IMetadataCommand;

/// <summary>Append an audit log entry.</summary>
/// <param name="UserId">Id of the user who acted.</param>
/// <param name="Action">Name of the message.</param>
/// <param name="Target">Path or id the action was applied to.</param>
/// <param name="Allowed">True when the action was allowed.</param>
/// <param name="At">UTC time decided before logging.</param>
public sealed record RecordAudit(string UserId, string Action, string Target, bool Allowed, DateTime At) : IMetadataCommand;
